// softer: only hard failures for php/json/openssl/app/routes/writable
$hardOk = true;
foreach ($checks as $c) {
    if (in_array($c['label'], ['PHP >= 8.1', 'ext-json', 'ext-openssl', 'Data dir writable', 'app/ present', 'routes/ present'], true) && !$c['ok']) {
        $hardOk = false;
    }
}

if ($_SERVER['REQUEST_METHOD'] === 'POST' && ($_POST['action'] ?? '') === 'install') {
    if (!$hardOk) {
        $errors[] = 'Fix hard requirements before installing.';
    } else {
        $appUrl = rtrim(trim((string)($_POST['APP_URL'] ?? '')), '/');
        $adminToken = trim((string)($_POST['ADMIN_TOKEN'] ?? ''));
        $fedSecret = trim((string)($_POST['FEDERATION_SECRET'] ?? ''));
        $dbDriver = in_array($_POST['DB_DRIVER'] ?? '', ['sqlite', 'mysql'], true) ? $_POST['DB_DRIVER'] : 'sqlite';
        if ($appUrl === '') {
            $scheme = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off') ? 'https' : 'http';
            $host = $_SERVER['HTTP_HOST'] ?? 'localhost';
            $appUrl = $scheme . '://' . $host . '/nyx';
        }
        if ($adminToken === '') {
            $adminToken = bin2hex(random_bytes(16));
        }
        if ($fedSecret === '') {
            $fedSecret = bin2hex(random_bytes(16));
        }
        $vars = [
            'APP_NAME' => trim((string)($_POST['APP_NAME'] ?? 'NYX')) ?: 'NYX',
            'APP_ENV' => 'production',
            'APP_DEBUG' => isset($_POST['APP_DEBUG']) ? 'true' : 'false',
            'APP_URL' => $appUrl,
            'APP_KEY' => nyx_gen_key(),
            'DB_DRIVER' => $dbDriver,
            'DB_DATABASE' => 'data/nyx.sqlite',
            'DB_HOST' => trim((string)($_POST['DB_HOST'] ?? '127.0.0.1')),
            'DB_PORT' => trim((string)($_POST['DB_PORT'] ?? '3306')),
            'DB_DATABASE_NAME' => trim((string)($_POST['DB_DATABASE_NAME'] ?? 'nyx')),
            'DB_USERNAME' => trim((string)($_POST['DB_USERNAME'] ?? '')),
            'DB_PASSWORD' => (string)($_POST['DB_PASSWORD'] ?? ''),
            'FEDERATION_ENABLED' => isset($_POST['FEDERATION_ENABLED']) ? 'true' : 'false',
            'ADMIN_TOKEN' => $adminToken,
            'FEDERATION_SECRET' => $fedSecret,
        ];
        nyx_ensure_dirs($dataDir, $nyxBase);
        if (!nyx_write_env($envFile, $vars)) {
            $errors[] = 'Could not write .env — check permissions on ' . $nyxBase;
        } else {
            // sqlite touch
            if ($dbDriver === 'sqlite') {
                $sqlite = $dataDir . '/nyx.sqlite';
                if (!is_file($sqlite)) {
                    @touch($sqlite);
                    @chmod($sqlite, 0640);
                }
            }
            nyx_disable_installer($lockFile, __DIR__);
            $success = true;
            $generated = [
                'APP_URL' => $appUrl,
                'ADMIN_TOKEN' => $adminToken,
                'FEDERATION_SECRET' => $fedSecret,
            ];
        }
    }
}

