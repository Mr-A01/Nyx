declare(strict_types=1);

header('X-Robots-Tag: noindex, nofollow');
header('Cache-Control: no-store');

$nyxBase = dirname(__DIR__, 2); // .../nyx
if (!is_dir($nyxBase . '/app') && is_dir(dirname(__DIR__) . '/app')) {
    $nyxBase = dirname(__DIR__);
}
$dataDir = is_dir($nyxBase . '/data') ? $nyxBase . '/data' : $nyxBase . '/storage/data';
$lockFile = $dataDir . '/install.lock';
$envFile = $nyxBase . '/.env';
$envExample = $nyxBase . '/.env.example';

function nyx_h(string $s): string {
    return htmlspecialchars($s, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
}

function nyx_is_locked(string $lockFile): bool {
    return is_file($lockFile);
}

function nyx_requirements(): array {
    $checks = [];
    $checks[] = ['label' => 'PHP >= 8.1', 'ok' => version_compare(PHP_VERSION, '8.1.0', '>='), 'detail' => PHP_VERSION];
    $checks[] = ['label' => 'ext-json', 'ok' => extension_loaded('json'), 'detail' => extension_loaded('json') ? 'yes' : 'missing'];
    $checks[] = ['label' => 'ext-mbstring', 'ok' => extension_loaded('mbstring'), 'detail' => extension_loaded('mbstring') ? 'yes' : 'recommended'];
    $checks[] = ['label' => 'ext-openssl', 'ok' => extension_loaded('openssl'), 'detail' => extension_loaded('openssl') ? 'yes' : 'missing'];
    $checks[] = ['label' => 'ext-pdo_sqlite OR pdo_mysql', 'ok' => extension_loaded('pdo_sqlite') || extension_loaded('pdo_mysql'), 'detail' => extension_loaded('pdo_sqlite') ? 'sqlite' : (extension_loaded('pdo_mysql') ? 'mysql' : 'none')];
    $checks[] = ['label' => 'ext-curl (federation)', 'ok' => extension_loaded('curl'), 'detail' => extension_loaded('curl') ? 'yes' : 'optional'];
    global $nyxBase, $dataDir;
    $checks[] = ['label' => 'Base readable', 'ok' => is_dir($nyxBase) && is_readable($nyxBase), 'detail' => $nyxBase];
    $writableData = is_dir($dataDir) ? is_writable($dataDir) : is_writable(dirname($dataDir));
    $checks[] = ['label' => 'Data dir writable', 'ok' => $writableData, 'detail' => $dataDir];
    $checks[] = ['label' => 'app/ present', 'ok' => is_dir($nyxBase . '/app'), 'detail' => is_dir($nyxBase . '/app') ? 'ok' : 'missing'];
    $checks[] = ['label' => 'routes/ present', 'ok' => is_dir($nyxBase . '/routes'), 'detail' => is_dir($nyxBase . '/routes') ? 'ok' : 'missing'];
    return $checks;
}

function nyx_gen_key(int $bytes = 32): string {
    return 'base64:' . base64_encode(random_bytes($bytes));
}

function nyx_write_env(string $path, array $vars): bool {
    $lines = [
        '# NYX Relay — generated by install wizard ' . gmdate('c'),
        'APP_NAME=' . ($vars['APP_NAME'] ?? 'NYX'),
        'APP_ENV=' . ($vars['APP_ENV'] ?? 'production'),
        'APP_DEBUG=' . (($vars['APP_DEBUG'] ?? 'false') === 'true' ? 'true' : 'false'),
        'APP_URL=' . ($vars['APP_URL'] ?? ''),
        'APP_KEY=' . ($vars['APP_KEY'] ?? ''),
        '',
        'NYX_PROTOCOL=3',
        'NYX_VERSION=1.45.0-scale',
        'NYX_RELEASE_CHANNEL=stable',
        '',
        'DB_DRIVER=' . ($vars['DB_DRIVER'] ?? 'sqlite'),
        'DB_DATABASE=' . ($vars['DB_DATABASE'] ?? 'data/nyx.sqlite'),
        'DB_HOST=' . ($vars['DB_HOST'] ?? '127.0.0.1'),
        'DB_PORT=' . ($vars['DB_PORT'] ?? '3306'),
        'DB_DATABASE_NAME=' . ($vars['DB_DATABASE_NAME'] ?? 'nyx'),
        'DB_USERNAME=' . ($vars['DB_USERNAME'] ?? ''),
        'DB_PASSWORD=' . ($vars['DB_PASSWORD'] ?? ''),
        '',
        'CACHE_DRIVER=file',
        'QUEUE_DRIVER=file',
        'LOG_CHANNEL=stack',
        'LOG_LEVEL=info',
        '',
        'FEDERATION_ENABLED=' . (($vars['FEDERATION_ENABLED'] ?? 'true') === 'true' ? 'true' : 'false'),
        'MESH_MAX_FRIENDS=6',
        'MESH_MAX_PEERS=32',
        '',
        'RATE_LIMIT_MAX=180',
        'RATE_LIMIT_WINDOW=60',
        '',
        'ADMIN_TOKEN=' . ($vars['ADMIN_TOKEN'] ?? ''),
        'FEDERATION_SECRET=' . ($vars['FEDERATION_SECRET'] ?? ''),
        '',
    ];
    return file_put_contents($path, implode("\n", $lines) . "\n") !== false;
}

function nyx_ensure_dirs(string $dataDir, string $nyxBase): array {
    $made = [];
    $dirs = [
        $dataDir,
        $dataDir . '/users',
        $dataDir . '/spaces',
        $dataDir . '/memberships',
        $dataDir . '/messages',
        $dataDir . '/identity/usernames',
        $dataDir . '/sessions',
        $dataDir . '/security',
        $dataDir . '/crypto',
        $dataDir . '/audit',
        $nyxBase . '/storage',
        $nyxBase . '/storage/logs',
    ];
    foreach ($dirs as $d) {
        if (!is_dir($d)) {
            if (@mkdir($d, 0750, true)) {
                $made[] = $d;
            }
        }
    }
    return $made;
}

function nyx_disable_installer(string $lockFile, string $installDir): void {
    $payload = [
        'installed_at' => gmdate('c'),
        'php' => PHP_VERSION,
        'host' => $_SERVER['HTTP_HOST'] ?? 'cli',
        'disabled' => true,
    ];
    @file_put_contents($lockFile, json_encode($payload, JSON_PRETTY_PRINT));
    // Hard disable: drop a deny htaccess inside install/
    $deny = $installDir . '/.htaccess';
    @file_put_contents($deny, "Require all denied\nDeny from all\n");
    // Marker file so index refuses even if htaccess ignored
    @file_put_contents($installDir . '/INSTALLED', "NYX install completed. This wizard is permanently disabled.\n");
}

